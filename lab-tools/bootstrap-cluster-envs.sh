#!/usr/bin/env bash
# Configure a lab member's shell to use the Cheminformatics golden environments.
# This is safe to rerun and never writes into the shared prefix.
set -euo pipefail

SHARED_ROOT="${PYMACS_LAB_TOOLS_ROOT:-/projectnb/cheminfo/share/pymacs-lab/lab-tools}"
PROFILE_DIR="$HOME/.config/pymacs"
PROFILE_FILE="$PROFILE_DIR/lab-tools-env.sh"
BASHRC="$HOME/.bashrc"
MARKER_BEGIN="# BEGIN PYMACS LAB TOOLS"
MARKER_END="# END PYMACS LAB TOOLS"

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

[[ -r "$SHARED_ROOT/bootstrap-cluster-envs.sh" ]] || die "Shared lab-tools directory is unavailable: $SHARED_ROOT"

case "$(uname -m)" in
  ppc64le) PLATFORM="triton"; AVAILABLE="cgenff mdanalysis vina_env" ;;
  x86_64) PLATFORM="pegasus"; AVAILABLE="vina_env" ;;
  *) die "Unsupported platform: $(uname -m)" ;;
esac

ENV_ROOT="$SHARED_ROOT/$PLATFORM/envs"
for env_name in $AVAILABLE; do
  [[ -x "$ENV_ROOT/$env_name/bin/python" ]] || die "Missing shared $env_name environment at $ENV_ROOT/$env_name"
done

mkdir -p "$PROFILE_DIR"
chmod 700 "$PROFILE_DIR"
cat > "$PROFILE_FILE" <<EOF
# Generated by PyMACS lab-tools bootstrap. Safe to replace on rerun.
export PYMACS_LAB_TOOLS_ROOT="$SHARED_ROOT"
export PYMACS_LAB_PLATFORM="$PLATFORM"
export PYMACS_LAB_ENV_ROOT="$ENV_ROOT"
export PYMACS_LAB_ENVIRONMENTS="$AVAILABLE"
pymacs-env() {
    local requested="\${1:-}"
    case " \$PYMACS_LAB_ENVIRONMENTS " in
        *" \$requested "*) source "\$PYMACS_LAB_ENV_ROOT/\$requested/bin/activate" ;;
        *) printf 'Available PyMACS environments on %s: %s\\n' "\$PYMACS_LAB_PLATFORM" "\$PYMACS_LAB_ENVIRONMENTS" >&2; return 2 ;;
    esac
}
EOF
chmod 600 "$PROFILE_FILE"

if ! grep -Fqx "$MARKER_BEGIN" "$BASHRC" 2>/dev/null; then
  {
    printf '\n%s\n' "$MARKER_BEGIN"
    printf '[ -r "$HOME/.config/pymacs/lab-tools-env.sh" ] && . "$HOME/.config/pymacs/lab-tools-env.sh"\n'
    printf '%s\n' "$MARKER_END"
  } >> "$BASHRC"
fi

printf 'PyMACS lab environments are ready on %s.\n' "$PLATFORM"
printf 'Run: source ~/.bashrc && pymacs-env [ %s ]\n' "$AVAILABLE"
